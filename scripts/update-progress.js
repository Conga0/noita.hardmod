// Updates the comment at the end of each .yaml file in `locale`
// to include 

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import * as YAML from "js-yaml";

const DEFAULT_LOCALE = "01_en.yaml";

const en = YAML.load(readFileSync(`locale/${DEFAULT_LOCALE}`));
const comment = "# --- Missing Translations ---";

for (const file of readdirSync("locale")) {
	if (file == DEFAULT_LOCALE || !file.endsWith("yaml")) continue;

	const path = `locale/${file}`;
	const raw = readFileSync(path, "utf8");
	const locale = YAML.load(raw);

	const missing = {};
	let count = 0;

	for (const key in en) {
		if (!(key in locale) || locale[key] == en[key]) {
			missing[key] = en[key];
			count++;
		}
	}

	const lines = raw.split("\n");
	const idx = lines.indexOf(comment);
	if (idx > -1) lines.splice(idx);
	if (!lines.at(-1).trim()) lines.pop();
	
	if (count) {
		console.log(path, "missing", count, "keys");
		lines.push(
			"", comment,
			"#",
			"# Generated by `scripts/update-progress.js`",
			"# Do not put anything after this comment, it can get auto-removed",
			"#\n",
		);
		
		lines.push(YAML.dump(missing, {
			lineWidth: -1,
			quoteStyle: "double"
		}));
	}

	writeFileSync(path, lines.join("\n"));
}
